import pathlib, pytest, re, sys
ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/oracle"))
import emit_symbols

GHIDRA = ROOT / "config/usam2/ghidra_functions.json"
SPLAT = ROOT / "config/usam2/symbol_addrs.txt"
ORPHAN = ROOT / "config/usam2/unplaced_symbols.txt"
LINE = re.compile(r'\S+ = 0x[0-9A-F]{8}; // type:(?:func|obj) size:0x[0-9A-F]+ '
                  r'provenance:(?:dwarf|ghidra)(?: dwarf_name:\S+)?$')

def _final():
    return emit_symbols.final(emit_symbols.build(ROOT / "orig/SLUS_207.11", GHIDRA))

def test_dwarf_functions_keep_their_names():
    placed, _ = _final()
    by_addr = {r["address"]: r for r in placed}
    assert by_addr[0x0021C420]["name"] == "sysInitScf"
    assert by_addr[0x0021C420]["size"] == 0x30
    assert by_addr[0x0021C420]["provenance"] == "dwarf"

def test_counts_are_reported_by_the_reader():
    placed, _ = _final()
    funcs = [r for r in placed if r["provenance"] == "dwarf" and r["kind"] == "func"]
    objs = [r for r in placed if r["provenance"] == "dwarf" and r["kind"] == "obj"]
    ghidra = [r for r in placed if r["provenance"] == "ghidra"]
    assert len(funcs) == 423
    assert len(objs) == 612
    assert len(ghidra) == 2738
    assert len(placed) == 3773

def test_no_symbol_is_placed_at_zero_and_no_address_is_shared():
    placed, _ = _final()
    assert [r["name"] for r in placed if r["address"] == 0] == []
    assert len({r["address"] for r in placed}) == len(placed)

def test_unplaced_objects_are_kept_in_their_own_file():
    placed, unplaced = _final()
    assert len(unplaced) == 27
    assert {r["kind"] for r in unplaced} == {"obj"}
    assert {r["provenance"] for r in unplaced} == {"dwarf"}
    assert {r["address"] for r in unplaced} == {0}
    # nothing is dropped: the objects split across both files still total 639
    assert len([r for r in placed + unplaced if r["kind"] == "obj"]) == 639

def test_duplicate_names_are_reported_not_dropped():
    placed, unplaced = _final()
    assert emit_symbols.duplicates(placed) == []
    assert emit_symbols.duplicates(unplaced) == []
    assert len(placed) + len(unplaced) == 3800     # renaming never drops a record

def test_files_carry_splat_syntax_and_the_unplaced_reason(tmp_path):
    placed, unplaced = _final()
    text = (tmp_path / "splat.txt")
    orphan = (tmp_path / "orphan.txt")
    emit_symbols.write(text, placed)
    emit_symbols.write_unplaced(orphan, unplaced)
    lines = text.read_text().splitlines()
    assert len(lines) == 3773
    assert all(LINE.match(l) for l in lines)
    assert "= 0x00000000;" not in text.read_text()
    assert text.read_text().count("provenance:ghidra") == 2738
    assert "sysInitScf = 0x0021C420; // type:func size:0x30 provenance:dwarf" in text.read_text()
    orphans = orphan.read_text().splitlines()
    assert len(orphans) == 27
    assert all(l.endswith("reason:no AT_location address")
               or " reason:no AT_location address dwarf_name:" in l for l in orphans)

def test_committed_files_match_a_fresh_run(tmp_path):
    """Including the borrowed names: the oracle's own output is what is committed."""
    records, borrowed = emit_symbols.apply_borrowed(
        emit_symbols.build(ROOT / "orig/SLUS_207.11", GHIDRA))
    placed, unplaced = emit_symbols.final(records)
    emit_symbols.write(tmp_path / "splat.txt", placed)
    emit_symbols.write_unplaced(tmp_path / "orphan.txt", unplaced)
    assert borrowed > 0                       # the borrow step is part of the committed file
    assert (tmp_path / "splat.txt").read_bytes() == SPLAT.read_bytes()
    assert (tmp_path / "orphan.txt").read_bytes() == ORPHAN.read_bytes()


BORROWED_LEDGER = """\
// Borrowed library names -- generated by tools/sdk/borrow.py; do not hand-edit.
sceGsResetGraph = 0x00100288; // type:func size:0x190 provenance:oni2 tier:bytes
sceScfGetLanguage = 0x0021BDD0; // type:func size:0x60 provenance:sdk152 tier:run
"""


def test_borrowed_names_rename_the_records_they_name(tmp_path):
    ledger = tmp_path / "borrowed_symbols.txt"
    ledger.write_text(BORROWED_LEDGER)
    records = [dict(name="func_00100288", address=0x00100288, size=0, kind="func",
                    provenance="ghidra"),
               dict(name="func_00100290", address=0x00100290, size=0, kind="func",
                    provenance="ghidra")]
    renamed, count = emit_symbols.apply_borrowed(records, ledger)
    assert count == 2
    by_address = {r["address"]: r for r in renamed}
    assert by_address[0x00100288]["name"] == "sceGsResetGraph"
    assert by_address[0x00100288]["provenance"] == "oni2"
    assert by_address[0x00100288]["size"] == 0        # splat still detects the bounds
    assert by_address[0x00100290]["name"] == "func_00100290"


def test_a_borrowed_name_for_an_address_with_no_record_is_added(tmp_path):
    """spimdisasm detects starts Ghidra did not list: the ledger names them too."""
    ledger = tmp_path / "borrowed_symbols.txt"
    ledger.write_text(BORROWED_LEDGER)
    records, _ = emit_symbols.apply_borrowed([], ledger)
    assert [(r["name"], hex(r["address"]), r["size"], r["kind"]) for r in records] == [
        ("sceGsResetGraph", "0x100288", 0, "func"),
        ("sceScfGetLanguage", "0x21bdd0", 0, "func")]


def test_a_borrowed_name_with_no_validated_size_is_refused(tmp_path):
    """`size:0x0` would mean nothing was checked: the ledger must carry the real number."""
    ledger = tmp_path / "borrowed_symbols.txt"
    ledger.write_text("sceGsResetGraph = 0x00100288; // type:func size:0x0 "
                      "provenance:oni2 tier:bytes\n")
    with pytest.raises(ValueError, match="positive whole number of instructions"):
        emit_symbols.apply_borrowed([], ledger)


def test_a_borrowed_name_that_lands_on_a_different_kind_of_symbol_is_refused(tmp_path):
    """A function name must not be hung on a data symbol."""
    ledger = tmp_path / "borrowed_symbols.txt"
    ledger.write_text(BORROWED_LEDGER)
    records = [dict(name="g_table", address=0x00100288, size=4, kind="obj",
                    provenance="dwarf")]
    with pytest.raises(ValueError, match="is a obj in this tree"):
        emit_symbols.apply_borrowed(records, ledger)


def test_a_borrowed_name_that_names_another_address_is_refused(tmp_path):
    ledger = tmp_path / "borrowed_symbols.txt"
    ledger.write_text("sceGsResetGraph = 0x00100288; // type:func size:0x190 "
                      "provenance:oni2 tier:bytes\n")
    records = [dict(name="sceGsResetGraph", address=0x0021C420, size=0, kind="func",
                    provenance="dwarf")]
    with pytest.raises(ValueError, match="already 0x0021C420's name"):
        emit_symbols.apply_borrowed(records, ledger)


def test_a_ledger_line_that_is_not_the_ledger_format_is_an_error(tmp_path):
    ledger = tmp_path / "borrowed_symbols.txt"
    ledger.write_text("sceGsResetGraph = 0x00100288; // size:190\n")
    with pytest.raises(ValueError, match="line 1"):
        emit_symbols.apply_borrowed([], ledger)


def test_no_ledger_is_no_renaming(tmp_path):
    records = [dict(name="func_00100288", address=0x00100288, size=0, kind="func",
                    provenance="ghidra")]
    assert emit_symbols.apply_borrowed(records, tmp_path / "absent.txt") == (records, 0)
